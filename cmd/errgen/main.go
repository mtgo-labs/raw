// Command errgen generates the Telegram RPC error catalog.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedPrefix = "// Code generated by cmd/errgen; DO NOT EDIT.\n"

type rawErrors struct {
	Base   map[string]int                `json:"base"`
	Errors map[string]rawErrorDefinition `json:"errors"`
}

type rawErrorDefinition struct {
	Code int    `json:"code"`
	Name string `json:"name"`
}

type errorConstant struct {
	Name  string
	Value string
}

type errorPattern struct {
	Constant string
	Prefix   string
	Suffix   string
}

type catalog struct {
	Codes    []errorConstant
	Errors   []errorConstant
	Patterns []errorPattern
}

func main() {
	root := flag.String("root", ".", "module root containing schema and tgerr")
	flag.Parse()

	if err := run(*root); err != nil {
		fmt.Fprintf(os.Stderr, "errgen: %v\n", err)
		os.Exit(1)
	}
}

func run(root string) error {
	input := filepath.Join(root, "schema", "raw-errors.json")
	data, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("read raw errors: %w", err)
	}
	var source rawErrors
	if err := json.Unmarshal(data, &source); err != nil {
		return fmt.Errorf("decode raw errors: %w", err)
	}
	value, err := buildCatalog(source)
	if err != nil {
		return err
	}
	output, err := render(value)
	if err != nil {
		return err
	}
	if err := writeGenerated(
		filepath.Join(root, "tgerr", "errors_gen.go"),
		output,
	); err != nil {
		return err
	}
	return nil
}

func buildCatalog(source rawErrors) (catalog, error) {
	if len(source.Base) == 0 || len(source.Errors) == 0 {
		return catalog{}, errors.New("raw error catalog is empty")
	}

	result := catalog{
		Codes: make([]errorConstant, 0, len(source.Base)),
	}
	codeNames := make(map[string]string, len(source.Base))
	for name, code := range source.Base {
		if code <= 0 {
			return catalog{}, fmt.Errorf("base error %q has invalid code %d", name, code)
		}
		goName, err := goIdentifier("Code", name)
		if err != nil {
			return catalog{}, fmt.Errorf("base error %q: %w", name, err)
		}
		if previous := codeNames[goName]; previous != "" && previous != name {
			return catalog{}, fmt.Errorf(
				"base errors %q and %q normalize to %s",
				previous,
				name,
				goName,
			)
		}
		codeNames[goName] = name
		result.Codes = append(result.Codes, errorConstant{
			Name:  goName,
			Value: fmt.Sprintf("%d", code),
		})
	}

	byType := make(map[string]errorConstant, len(source.Errors))
	goNames := make(map[string]string, len(source.Errors))
	for key, definition := range source.Errors {
		if definition.Code == 0 {
			return catalog{}, fmt.Errorf(
				"error %q has invalid code %d",
				key,
				definition.Code,
			)
		}
		if definition.Name != key {
			return catalog{}, fmt.Errorf(
				"error key %q has mismatched name %q",
				key,
				definition.Name,
			)
		}
		normalized, err := normalizeErrorType(key)
		if err != nil {
			return catalog{}, fmt.Errorf("error %q: %w", key, err)
		}
		goName := errorNameOverrides[normalized]
		if goName == "" {
			goName, err = goIdentifier("Err", normalized)
			if err != nil {
				return catalog{}, fmt.Errorf("error %q: %w", key, err)
			}
		}
		if previous := goNames[goName]; previous != "" && previous != normalized {
			return catalog{}, fmt.Errorf(
				"error types %q and %q normalize to %s",
				previous,
				normalized,
				goName,
			)
		}
		goNames[goName] = normalized
		byType[normalized] = errorConstant{Name: goName, Value: normalized}

		if !strings.Contains(key, "%d") {
			continue
		}
		if strings.Count(key, "%d") != 1 {
			return catalog{}, fmt.Errorf("pattern must contain exactly one %%d")
		}
		prefix, suffix, _ := strings.Cut(key, "%d")
		if prefix == "" {
			return catalog{}, fmt.Errorf("pattern has an empty prefix")
		}
		result.Patterns = append(result.Patterns, errorPattern{
			Constant: goName,
			Prefix:   prefix,
			Suffix:   suffix,
		})
	}

	result.Errors = make([]errorConstant, 0, len(byType))
	for _, definition := range byType {
		result.Errors = append(result.Errors, definition)
	}
	sort.Slice(result.Codes, func(i, j int) bool {
		return result.Codes[i].Name < result.Codes[j].Name
	})
	sort.Slice(result.Errors, func(i, j int) bool {
		return result.Errors[i].Name < result.Errors[j].Name
	})
	sort.Slice(result.Patterns, func(i, j int) bool {
		if result.Patterns[i].Prefix != result.Patterns[j].Prefix {
			return result.Patterns[i].Prefix < result.Patterns[j].Prefix
		}
		return result.Patterns[i].Suffix < result.Patterns[j].Suffix
	})
	return result, nil
}

func normalizeErrorType(value string) (string, error) {
	if value == "" {
		return "", errors.New("empty error type")
	}
	for index := 0; index < len(value); index++ {
		current := value[index]
		if current >= 'A' && current <= 'Z' ||
			current >= 'a' && current <= 'z' ||
			current >= '0' && current <= '9' ||
			current == '_' {
			continue
		}
		if current == '%' &&
			index+1 < len(value) &&
			value[index+1] == 'd' {
			index++
			continue
		}
		return "", fmt.Errorf("invalid character %q", current)
	}
	normalized := strings.ReplaceAll(value, "%d", "")
	for strings.Contains(normalized, "__") {
		normalized = strings.ReplaceAll(normalized, "__", "_")
	}
	normalized = strings.Trim(normalized, "_")
	if normalized == "" {
		return "", errors.New("empty normalized error type")
	}
	return normalized, nil
}

func goIdentifier(prefix, value string) (string, error) {
	parts := strings.Split(value, "_")
	var name strings.Builder
	name.WriteString(prefix)
	for _, part := range parts {
		if part == "" {
			continue
		}
		if override := identifierOverrides[part]; override != "" {
			name.WriteString(override)
			continue
		}
		name.WriteString(strings.ToUpper(part[:1]))
		name.WriteString(strings.ToLower(part[1:]))
	}
	if name.Len() == len(prefix) {
		return "", errors.New("identifier has no name")
	}
	return name.String(), nil
}


func render(value catalog) ([]byte, error) {
	var output strings.Builder
	output.WriteString(generatedPrefix)
	output.WriteString("\npackage tgerr\n\n")

	output.WriteString("// Telegram RPC error codes.\nconst (\n")
	for _, code := range value.Codes {
		fmt.Fprintf(&output, "\t%s = %s\n", code.Name, code.Value)
	}
	output.WriteString(")\n\n")

	output.WriteString("// Telegram RPC error types.\nconst (\n")
	for _, definition := range value.Errors {
		fmt.Fprintf(&output, "\t%s = %q\n", definition.Name, definition.Value)
	}
	output.WriteString(")\n\n")

	for _, definition := range value.Errors {
		helper := strings.TrimPrefix(definition.Name, "Err")
		fmt.Fprintf(
			&output,
			"// Is%s reports whether err has type %s.\n",
			helper,
			definition.Name,
		)
		fmt.Fprintf(&output, "func Is%s(err error) bool {\n", helper)
		fmt.Fprintf(&output, "\treturn Is(err, %s)\n", definition.Name)
		output.WriteString("}\n\n")
	}

	output.WriteString(
		"func matchParameterized(message string) (string, int32, bool) {\n" +
			"\tif message == \"\" {\n" +
			"\t\treturn \"\", 0, false\n" +
			"\t}\n" +
			"\tswitch message[0] {\n",
	)
	groups := make(map[byte][]errorPattern)
	for _, pattern := range value.Patterns {
		groups[pattern.Prefix[0]] = append(groups[pattern.Prefix[0]], pattern)
	}
	firstBytes := make([]int, 0, len(groups))
	for first := range groups {
		firstBytes = append(firstBytes, int(first))
	}
	sort.Ints(firstBytes)
	for _, first := range firstBytes {
		fmt.Fprintf(&output, "\tcase %q:\n", byte(first))
		for _, pattern := range groups[byte(first)] {
			fmt.Fprintf(
				&output,
				"\t\tif argument, ok := matchDecimalPattern(message, %q, %q); ok {\n",
				pattern.Prefix,
				pattern.Suffix,
			)
			fmt.Fprintf(
				&output,
				"\t\t\treturn %s, argument, true\n",
				pattern.Constant,
			)
			output.WriteString("\t\t}\n")
		}
	}
	output.WriteString(
		"\t}\n" +
			"\treturn \"\", 0, false\n" +
			"}\n",
	)

	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated catalog: %w", err)
	}
	return formatted, nil
}

func writeGenerated(path string, data []byte) error {
	current, err := os.ReadFile(path)
	if err == nil {
		if bytes.Equal(current, data) {
			return nil
		}
		if !bytes.HasPrefix(current, []byte(generatedPrefix)) {
			return fmt.Errorf("refuse to overwrite non-generated file %q", path)
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("read output: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".errgen-*")
	if err != nil {
		return fmt.Errorf("create temporary output: %w", err)
	}
	temporaryName := temporary.Name()
	defer os.Remove(temporaryName)
	if err := temporary.Chmod(0o644); err != nil {
		_ = temporary.Close()
		return fmt.Errorf("set output mode: %w", err)
	}
	if _, err := temporary.Write(data); err != nil {
		_ = temporary.Close()
		return fmt.Errorf("write output: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close output: %w", err)
	}
	if err := os.Rename(temporaryName, path); err != nil {
		return fmt.Errorf("replace output: %w", err)
	}
	return nil
}

// Command rsagen generates the pinned Telegram RSA public-key registry.
package main

import (
	"bytes"
	"crypto/sha1"
	"crypto/x509"
	"encoding/binary"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"math/big"
	"os"
	"path/filepath"
	"strings"
)

const generatedPrefix = "// Code generated by cmd/rsagen; DO NOT EDIT.\n"

type keyRecord struct {
	fingerprint uint64
	old         bool
	modulus     []byte
	exponent    []byte
}

func main() {
	root := flag.String("root", ".", "module root")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintf(os.Stderr, "rsagen: %v\n", err)
		os.Exit(1)
	}
}

func run(root string) error {
	records, err := loadKeys(filepath.Join(root, "schema", "rsa-keys.txt"))
	if err != nil {
		return err
	}
	source, err := render(records)
	if err != nil {
		return err
	}
	path := filepath.Join(root, "internal", "cryptoutil", "rsa_keys_gen.go")
	return writeAtomic(path, source)
}

func loadKeys(path string) ([]keyRecord, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read RSA keys: %w", err)
	}

	var records []keyRecord
	old := false
	remaining := data
	for len(remaining) > 0 {
		block, rest := pem.Decode(remaining)
		if block == nil {
			if !onlyRSAKeyComments(remaining) {
				return nil, errors.New("RSA key input contains invalid trailing data")
			}
			break
		}
		consumed := len(remaining) - len(rest)
		if bytes.Contains(remaining[:consumed], []byte("### OLD ###")) {
			old = true
		}
		publicKey, err := x509.ParsePKCS1PublicKey(block.Bytes)
		if err != nil {
			return nil, fmt.Errorf("parse RSA public key: %w", err)
		}
		if publicKey.N.BitLen() != 2048 || publicKey.E < 3 || publicKey.E%2 == 0 {
			return nil, errors.New("RSA registry contains an invalid public key")
		}
		modulus := publicKey.N.Bytes()
		exponent := big.NewInt(int64(publicKey.E)).Bytes()
		records = append(records, keyRecord{
			fingerprint: publicKeyFingerprint(modulus, exponent),
			old:         old,
			modulus:     modulus,
			exponent:    exponent,
		})
		remaining = rest
	}
	if len(records) != 10 {
		return nil, fmt.Errorf("RSA key count = %d, want 10", len(records))
	}
	return records, nil
}

func onlyRSAKeyComments(data []byte) bool {
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line != "" && !strings.HasPrefix(line, "#") && line != "-----END OLD KEYS-----" {
			return false
		}
	}
	return true
}

func publicKeyFingerprint(modulus, exponent []byte) uint64 {
	serialized := appendTLBytes(nil, modulus)
	serialized = appendTLBytes(serialized, exponent)
	digest := sha1.Sum(serialized)
	return binary.LittleEndian.Uint64(digest[len(digest)-8:])
}

func appendTLBytes(output, value []byte) []byte {
	length := len(value)
	if length <= 253 {
		output = append(output, byte(length))
	} else {
		output = append(output, 254, byte(length), byte(length>>8), byte(length>>16))
	}
	output = append(output, value...)
	for len(output)%4 != 0 {
		output = append(output, 0)
	}
	return output
}

func render(records []keyRecord) ([]byte, error) {
	var source strings.Builder
	source.WriteString(generatedPrefix)
	source.WriteString("package cryptoutil\n\n")
	source.WriteString("import (\n\t\"crypto/rsa\"\n\t\"math/big\"\n)\n\n")
	source.WriteString("type telegramRSAKey struct {\n\tfingerprint uint64\n\told bool\n\tmodulus [256]byte\n\texponent [3]byte\n}\n\n")
	source.WriteString("var telegramRSAKeys = [...]telegramRSAKey{\n")
	for _, record := range records {
		fmt.Fprintf(&source, "\t{fingerprint: 0x%016x, old: %t, modulus: [256]byte{", record.fingerprint, record.old)
		writeByteLiteral(&source, record.modulus)
		source.WriteString("}, exponent: [3]byte{")
		writeByteLiteral(&source, record.exponent)
		source.WriteString("}},\n")
	}
	source.WriteString("}\n\n")
	source.WriteString("// FindTelegramRSAKey returns the first matching new key, or an old key\n")
	source.WriteString("// when allowOld is true or no new key matches.\n")
	source.WriteString("func FindTelegramRSAKey(fingerprints []uint64, allowOld bool) (*rsa.PublicKey, uint64, bool) {\n")
	source.WriteString("\tfor _, fingerprint := range fingerprints {\n\t\tfor index := range telegramRSAKeys {\n\t\t\tkey := &telegramRSAKeys[index]\n\t\t\tif key.fingerprint == fingerprint && (allowOld || !key.old) {\n\t\t\t\treturn key.publicKey(), fingerprint, true\n\t\t\t}\n\t\t}\n\t}\n")
	source.WriteString("\tif !allowOld {\n\t\treturn FindTelegramRSAKey(fingerprints, true)\n\t}\n\treturn nil, 0, false\n}\n\n")
	source.WriteString("func (key *telegramRSAKey) publicKey() *rsa.PublicKey {\n")
	source.WriteString("\treturn &rsa.PublicKey{N: new(big.Int).SetBytes(key.modulus[:]), E: int(key.exponent[0])<<16 | int(key.exponent[1])<<8 | int(key.exponent[2])}\n}\n")
	return format.Source([]byte(source.String()))
}

func writeByteLiteral(source *strings.Builder, value []byte) {
	for index, item := range value {
		if index != 0 {
			source.WriteString(", ")
		}
		fmt.Fprintf(source, "0x%02x", item)
	}
}

func writeAtomic(path string, data []byte) error {
	current, err := os.ReadFile(path)
	if err == nil && !bytes.HasPrefix(current, []byte(generatedPrefix)) {
		return errors.New("refusing to overwrite non-generated RSA registry")
	}
	if err == nil && bytes.Equal(current, data) {
		return nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read generated RSA registry: %w", err)
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".rsagen-*")
	if err != nil {
		return fmt.Errorf("create temporary RSA registry: %w", err)
	}
	temporaryName := temporary.Name()
	defer os.Remove(temporaryName)
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return fmt.Errorf("write generated RSA registry: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close generated RSA registry: %w", err)
	}
	if err := os.Rename(temporaryName, path); err != nil {
		return fmt.Errorf("replace generated RSA registry: %w", err)
	}
	return nil
}
